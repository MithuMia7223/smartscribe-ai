// Gemini API Direct Handler
async function callGeminiAPI(prompt, toolType, language) {
    const apiKey = process.env.GEMINI_API_KEY;

    if (apiKey && apiKey.startsWith('AIzaSy')) {
        try {
            const systemInstructions = {
                social: `You are an expert Social Media Specialist. Create an engaging, viral-style social media post with relevant emojis and trending hashtags in ${language}.`,
                email: `You are a professional Business Communication Specialist. Write a clear, polite, and persuasive professional email in ${language}.`,
                essay: `You are an Academic Writing Assistant. Write a comprehensive essay in ${language}.`,
                cover_letter: `You are a Career Coach. Write an impressive job cover letter in ${language}.`
            };

            const instruction = systemInstructions[toolType] || `You are a helpful AI content writer in ${language}.`;
            const fullPrompt = `${instruction}\n\nUser Request: ${prompt}\n\nProvide direct final output. At the very end add: "\n\n✨ Generated by SmartScribe AI - Free AI Content Tool"`;

            const response = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${apiKey}`, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ contents: [{ parts: [{ text: fullPrompt }] }] })
            });

            const data = await response.json();
            if (data.candidates && data.candidates[0] && data.candidates[0].content) {
                return data.candidates[0].content.parts[0].text;
            }
        } catch (e) {
            console.error('Gemini API fetch error, falling back to Native AI Generator:', e.message);
        }
    }

    // Smart Native AI fallback generator
    return generateNativeAIContent(prompt, toolType, language);
}

// API Endpoint
app.post('/api/generate', async (req, res) => {
    try {
        const { prompt, toolType, language } = req.body;
        if (!prompt) {
            return res.status(400).json({ error: 'Prompt is required' });
        }

        const result = await callGeminiAPI(prompt, toolType || 'social', language || 'Bangla');
        res.json({ success: true, result });
    } catch (err) {
        res.status(500).json({ error: err.message });
    }
});

// Serve frontend SPA fallback
app.get('*', (req, res) => {
    res.sendFile(path.join(__dirname, 'public', 'index.html'));
});

app.listen(PORT, () => {
    console.log(`🚀 SmartScribe AI server running at http://localhost:${PORT}`);
});
